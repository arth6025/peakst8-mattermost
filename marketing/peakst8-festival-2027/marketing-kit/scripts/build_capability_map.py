#!/usr/bin/env python3
"""Write docs/CAPABILITY-MAP.md: every verified MCP tool, Space and model → the skills that use it, plus unused capabilities."""
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
cap = json.loads((ROOT / "registry/capabilities.json").read_text())
spaces = json.loads((ROOT / "registry/spaces.json").read_text())["spaces"]
reg = json.loads((ROOT / "registry/skills.json").read_text())["skills"]

tool_use, space_use, model_use, node_use = defaultdict(list), defaultdict(list), defaultdict(list), defaultdict(list)
for s in reg:
    for t in s.get("mcp_tools") or []:
        tool_use[t].append(s["id"])
    for sp in s.get("spaces") or []:
        space_use[sp["spaceId"]].append(f"{s['id']} ({sp.get('role','')})")
    for kind, ids in (s.get("models") or {}).items():
        for m in ids or []:
            model_use[m].append(s["id"])
    for k in s.get("node_kinds") or []:
        node_use[k].append(s["id"])

L = ["# Capability map", "",
     f"Verified against `{cap['server']}` on {cap['verified_on']}. Generated by `scripts/build_capability_map.py` from `registry/*.json`. "
     "Every row is a capability the server exposes today; the right column lists the skills that call it. An empty right column is an unused capability, which is a roadmap candidate.", ""]
L += ["## MCP tools", "", "| Group | Tool | Used by |", "|---|---|---|"]
for g, tools in cap["tool_groups"].items():
    for t in tools:
        L.append(f"| {g} | `{t}` | {', '.join(f'`{x}`' for x in sorted(tool_use.get(t, []))) or '(unused)'} |")
L += ["", "## Image models", "", "| Model | Provider | Max refs | Used by |", "|---|---|---|---|"]
for m in cap["models"]["image"]["list"]:
    L.append(f"| `{m['id']}` | {m['provider']} | {(m.get('constraints') or {}).get('maxReferenceImages','?')} | {', '.join(f'`{x}`' for x in sorted(model_use.get(m['id'], []))) or '(unused)'} |")
L += ["", "## Video models", "", "| Model | Provider | Durations | Used by |", "|---|---|---|---|"]
for m in cap["models"]["video"]["list"]:
    d = (m.get("options") or {}).get("duration", [])
    dd = f"{d[0]}–{d[-1]} s" if d else "?"
    L.append(f"| `{m['id']}` | {m['provider']} | {dd} | {', '.join(f'`{x}`' for x in sorted(model_use.get(m['id'], []))) or '(unused)'} |")
L += ["", "## Canvas node kinds", "", "| Kind | Used by (skills that author canvases) |", "|---|---|"]
for k in cap["node_kinds"]:
    L.append(f"| `{k}` | {', '.join(f'`{x}`' for x in sorted(node_use.get(k, []))) or '' } |")
L += ["", "## Published Spaces", "", "| Space | Domain | Output | Used by |", "|---|---|---|---|"]
for sp in sorted(spaces, key=lambda s: (s.get("domain", ""), s["slug"])):
    L.append(f"| `{sp['slug']}` | {sp.get('domain','')} | {'/'.join(sp.get('output', []))} | {', '.join(f'`{x}`' for x in sorted(space_use.get(sp['spaceId'], []))) or '(unused)'} |")
unused_tools = [t for t in cap["tools"] if t not in tool_use]
unused_spaces = [sp["slug"] for sp in spaces if sp["spaceId"] not in space_use]
L += ["", "## Unused today", "", f"Tools: {', '.join(f'`{t}`' for t in unused_tools) or 'none'}", "",
      f"Spaces ({len(unused_spaces)}): {', '.join(f'`{s}`' for s in unused_spaces) or 'none'}", ""]
(ROOT / "docs/CAPABILITY-MAP.md").write_text("\n".join(L))
print("wrote docs/CAPABILITY-MAP.md;", len(unused_tools), "unused tools,", len(unused_spaces), "unused spaces")
